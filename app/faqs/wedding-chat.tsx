'use client';
import { useChat } from '@ai-sdk/react';
import { DefaultChatTransport } from 'ai';
import Link from 'next/link';
import { useEffect, useRef, useState } from 'react';
import { z } from 'zod';
import { Button } from '@/components/ui/button';
import { codePointLength, messageText, QUESTION_LIMIT } from '@/lib/chat/contracts';
import { boundPairs, completedPair, pairsToMessages, restorePairs, savePairs, STORAGE_KEY } from '@/lib/chat/storage';
import { cn } from '@/lib/utils';
import type { CompletedPair } from '@/lib/chat/storage';

const REFERENCES = ['/faqs', '/schedule', '/travel', '/rsvp', '/registry', '/our-story'] as const;
const EXAMPLES = ['What time should I arrive?', 'What is the dress code?', 'Where is the welcome party?'];
const publicFailure = z.object({ code: z.string(), resetAt: z.number().optional() });
async function chatFetch(input: RequestInfo | URL, init?: RequestInit): Promise<Response> {
  const response = await fetch(input, init);
  if (response.ok)
    return response;
  let message = 'Chat is unavailable. Please use the FAQs or contact Sean or Eva.';
  try {
    const failure = publicFailure.safeParse(await response.json());
    if (response.status === 429 && failure.success && failure.data.resetAt && failure.data.resetAt < Date.parse('2026-10-19T05:00:00Z')) {
      const time = new Date(failure.data.resetAt).toLocaleString(undefined, { dateStyle: 'short', timeStyle: 'medium' });
      message = `The chat limit has been reached. You can try again after ${time}.`;
    } else if (response.status === 400 || response.status === 413) {
      message = 'This question or chat history is too large or invalid. Please clear chat and try a question of up to 500 characters.';
    }
  } catch {/* Keep the safe fallback, including for a proxy's HTML error page. */}
  throw new Error(message);
}
// One instance per FAQ mount. Only completed, bounded pairs enter subsequent requests.
const transport = new DefaultChatTransport({
  api: '/api/chat',
  fetch: chatFetch,
  prepareSendMessagesRequest: ({ messages }) => ({
    body: { messages: messages.slice(-7).map((message) => ({ id: message.id, role: message.role, parts: [{ type: 'text', text: messageText(message) }] })) },
  }),
});
const referenceLabel = (href: string): string => {
  if (href === '/faqs') return 'FAQs';
  if (href === '/rsvp') return 'RSVP';

  return href.slice(1).replace('-', ' ');
};

// eslint-disable-next-line max-lines-per-function -- Keep the tab lifecycle and its single panel together.
export function WeddingChat({ enabled }: {
  enabled: boolean;
}) {
  const [input, setInput] = useState('');
  const [restored, setRestored] = useState(false);
  const [notice, setNotice] = useState('');
  const [incomplete, setIncomplete] = useState(false);
  const [storageNotice, setStorageNotice] = useState(false);
  const pairs = useRef<CompletedPair[]>([]);
  const sending = useRef(false);
  const clearing = useRef(false);
  const mounted = useRef(false);
  const composer = useRef<HTMLTextAreaElement>(null);
  const transcript = useRef<HTMLDivElement>(null);
  const atBottom = useRef(true);
  const { clearError, messages, sendMessage, setMessages, status, stop } = useChat({
    transport,
    onFinish: ({ finishReason, isAbort, isDisconnect, isError, messages: finished }) => {
      sending.current = false;
      if (!mounted.current || clearing.current)
        return;
      const complete = !isAbort && !isError && !isDisconnect && finishReason === 'stop';
      setIncomplete(!complete);
      setNotice((previous) => {
        if (complete) return 'Answer complete.';
        if (isError || isDisconnect) return previous;

        return 'Answer stopped or incomplete. Please use the FAQs.';
      });
      const pair = complete ? completedPair(finished) : undefined;
      if (pair) {
        pairs.current = boundPairs([...pairs.current, pair]);
        try {
          if (!savePairs(sessionStorage, pairs.current))
            setStorageNotice(true);
        } catch {
          setStorageNotice(true);
        }
      }
    },
    onError: (error) => {
      sending.current = false;
      if (!mounted.current || clearing.current)
        return;
      setIncomplete(true);
      // Stream error text is generated by our server; network/parser errors use a fixed fallback.
      setNotice(error.message.startsWith('The chat limit') || error.message.startsWith('Chat is unavailable') ||
        error.message.startsWith('This question')
        ? error.message
        : 'The answer is incomplete. Please use the FAQs.');
    },
  });

  /* eslint-disable react-hooks/set-state-in-effect -- Restore external tab storage after mount and keep SSR deterministic. */
  useEffect(() => {
    mounted.current = true;
    try {
      pairs.current = restorePairs(sessionStorage.getItem(STORAGE_KEY));
    } catch {
      setStorageNotice(true);
    }
    setMessages(pairsToMessages(pairs.current));
    setRestored(true);

    return () => {
      mounted.current = false;
    };
  }, [setMessages]);
  /* eslint-enable react-hooks/set-state-in-effect */
  useEffect(() => {
    if (atBottom.current && transcript.current)
      transcript.current.scrollTop = transcript.current.scrollHeight;
  }, [messages]);
  const busy = status === 'submitted' || status === 'streaming';
  const length = codePointLength(input);
  const canSend = enabled && restored && !busy && length <= QUESTION_LIMIT && Boolean(input.trim());
  async function submit() {
    if (!canSend || sending.current)
      return;
    sending.current = true;
    clearing.current = false;
    clearError();
    setMessages(pairsToMessages(pairs.current));
    setIncomplete(false);
    setNotice('Getting an answer…');
    const text = input.trim();
    setInput('');
    composer.current?.focus();
    atBottom.current = true;
    await sendMessage({ text });
    sending.current = false;
  }
  async function clear() {
    clearing.current = true;
    await stop();
    sending.current = false;
    pairs.current = [];
    setMessages([]);
    clearError();
    setIncomplete(false);
    setNotice('Chat cleared.');
    try {
      if (!savePairs(sessionStorage, []))
        setStorageNotice(true);
    } catch {
      setStorageNotice(true);
    }
    composer.current?.focus();
  }

  return (
    <section aria-labelledby='wedding-chat-heading' className='mb-8 rounded-2xl border border-white/20 bg-white/10 p-4 text-left shadow-xl shadow-penn-blue/20 backdrop-blur-xs sm:p-6'>
      <h2 className='text-3xl font-league-gothic' id='wedding-chat-heading'>Ask about Forever Fest</h2>
      <p className='mt-1 text-white/80'>Answers from our wedding website.</p>
      {enabled ? (
        <>
          <div className='mt-4 flex flex-wrap gap-2'>
            {EXAMPLES.map((question) => (
              <Button
                key={question}
                className='h-auto whitespace-normal bg-white/10 text-white px-3 py-2 text-left text-base hover:bg-white/20 focus-visible:ring-lavender-pink'
                disabled={!restored || busy}
                type='button'
                onClick={() => {
                  setInput(question);
                  composer.current?.focus();
                }}
              >
                {question}
              </Button>
            ))}
          </div>
          <div
            ref={transcript}
            aria-label='Chat history'
            className={cn('mt-4 max-h-80 space-y-3 overflow-y-auto overscroll-contain', messages.length > 0 ? 'rounded-lg border border-white/10 p-3' : '')}
            role='region'
            tabIndex={messages.length > 0 ? 0 : -1}
            onScroll={(event) => {
              const element = event.currentTarget;
              atBottom.current = element.scrollHeight - element.scrollTop - element.clientHeight < 48;
            }}
          >
            {messages.map((message, index) => (
              <div key={message.id} className={cn('rounded-lg p-3', message.role === 'user' ? 'bg-white/10' : 'bg-penn-blue/30')}>
                <p className='mb-1 text-sm font-semibold text-lavender-pink'>{message.role === 'user' ? 'You' : 'Forever Fest'}</p>
                <p className='whitespace-pre-wrap wrap-anywhere text-base'>{messageText(message)}</p>
                {incomplete && index === messages.length - 1 && message.role === 'assistant' ? <p className='mt-2 text-sm text-papaya-whip'>Stopped or incomplete answer</p> : null}
              </div>
            ))}
          </div>
          <form
            className='mt-4'
            onSubmit={(event) => {
              event.preventDefault();
              void submit();
            }}
          >
            <label className='block text-sm font-semibold' htmlFor='wedding-chat-question'>Your question</label>
            <textarea
              ref={composer}
              aria-describedby='wedding-chat-counter wedding-chat-privacy'
              className='mt-2 min-h-24 w-full resize-y rounded-lg border border-white/30 bg-penn-blue/50 p-3 text-base text-white placeholder:text-white/50 focus-visible:outline-2 focus-visible:outline-lavender-pink disabled:opacity-60'
              disabled={!restored}
              id='wedding-chat-question'
              placeholder='Ask about the wedding…'
              rows={3}
              value={input}
              onChange={(event) => setInput(event.target.value)}
              onKeyDown={(event) => {
                if (event.key === 'Enter' && !event.shiftKey && !event.nativeEvent.isComposing && event.keyCode !== 229) {
                  event.preventDefault();
                  void submit();
                }
              }}
            />
            <div className='mt-2 flex flex-wrap items-center gap-3'>
              <span className={cn('mr-auto text-sm', length > QUESTION_LIMIT ? 'text-orange-200' : 'text-white/70')} id='wedding-chat-counter'>
                {length}
                /500 characters
              </span>
              {busy ? (
                <Button
                  className='bg-white/20 text-white text-lg hover:bg-white/30 focus-visible:ring-lavender-pink'
                  type='button'
                  onClick={() => {
                    setIncomplete(true);
                    setNotice('Answer stopped or incomplete. Please use the FAQs.');
                    void stop();
                  }}
                >
                  Stop
                </Button>
              ) : <Button className='bg-steel-pink text-white text-lg hover:bg-steel-pink/80 focus-visible:ring-lavender-pink' disabled={!canSend} type='submit'>Send</Button>}
              <Button className='bg-white/10 text-white text-lg hover:bg-white/20 focus-visible:ring-lavender-pink' disabled={!restored} type='button' onClick={() => {void clear();}}>Clear chat</Button>
            </div>
          </form>
        </>
      ) : (
        <p className='mt-4'>
          Chat is unavailable. Please use the
          <Link className='underline' href='/faqs#wedding-faqs'>FAQs below</Link>
          {' '}
          or contact Sean or Eva.
        </p>
      )}
      <p aria-atomic='true' aria-live='polite' className='mt-3 text-sm text-papaya-whip' role='status'>{notice}</p>
      {storageNotice ? <p className='mt-2 text-sm text-white/70'>Tab storage is unavailable. Chat will stay in memory for this visit.</p> : null}
      <nav aria-label='Website references' className='mt-4 flex flex-wrap gap-x-3 gap-y-2 border-t border-white/15 pt-3 text-sm'>
        <span className='font-semibold'>Website references</span>
        {REFERENCES.map((href) => <Link key={href} className='underline underline-offset-4 focus-visible:outline-2 focus-visible:outline-lavender-pink' href={href}>{referenceLabel(href)}</Link>)}
      </nav>
      <p className='mt-4 text-xs leading-relaxed text-white/70' id='wedding-chat-privacy'>AI answers can be wrong. Questions are processed by OpenAI. Please avoid sharing private information.</p>
    </section>
  );
}
